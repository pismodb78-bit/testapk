        sp = context.getSharedPreferences("pismo_emoji", Context.MODE_PRIVATE)
    }

    private val ready: Boolean get() = ::sp.isInitialized

    fun recent(): List<String> {
        if (!ready) return defaults
        val raw = sp.getString(KEY, "").orEmpty()
        val list = raw.split('\u0001').filter { it.isNotBlank() }
        return if (list.isEmpty()) defaults else list
    }

    /** Поднять эмодзи наверх списка недавних — как AddRecent на ПК. */
    fun remember(emoji: String) {
        if (!ready || emoji.isBlank()) return
        val list = ArrayList(recent())
        list.remove(emoji)
        list.add(0, emoji)
        while (list.size > MAX_RECENT) list.removeAt(list.size - 1)
        sp.edit().putString(KEY, list.joinToString("\u0001")).apply()
    }

    /** Поиск по всему каталогу — по подстроке названия категории. */
    fun search(query: String): List<String> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emptyList()
        return categories
            .filter { it.title.lowercase().contains(q) }
            .flatMap { it.items }
    }
}
